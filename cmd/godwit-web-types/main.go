// Generate the browser's wire types from the actual Go method signatures.
package main

import (
	"context"
	"encoding/json"
	"fmt"
	"github.com/godwit-email/godwit/core"
	"github.com/godwit-email/godwit/internal/webserver"
	"os"
	"reflect"
	"sort"
	"strings"
	"time"
	"unicode"
)

var defs = map[string]string{}

func ts(t reflect.Type) string {
	if t == reflect.TypeFor[time.Time]() {
		return "string"
	}
	if t == reflect.TypeFor[json.RawMessage]() {
		return "unknown"
	}
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64, reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Pointer:
		return ts(t.Elem()) + " | null"
	case reflect.Slice, reflect.Array:
		return "(" + ts(t.Elem()) + ")[] | null"
	case reflect.Map:
		return "Record<string, " + ts(t.Elem()) + "> | null"
	case reflect.Interface:
		return "unknown"
	case reflect.Chan:
		return ts(t.Elem())
	case reflect.Struct:
		name := t.Name()
		if name == "" {
			return "Record<string, unknown>"
		}
		parts := strings.Split(t.PkgPath(), "/")
		name = parts[len(parts)-1] + "_" + name
		name = strings.Map(func(r rune) rune {
			if unicode.IsLetter(r) || unicode.IsDigit(r) || r == '_' {
				return r
			}
			return '_'
		}, name)
		if _, ok := defs[name]; !ok {
			defs[name] = ""
			fields := []string{}
			embedded := []string{}
			for i := range t.NumField() {
				f := t.Field(i)
				if !f.IsExported() {
					continue
				}
				tag := strings.Split(f.Tag.Get("json"), ",")[0]
				if tag == "-" {
					continue
				}
				if f.Anonymous && tag == "" {
					embedded = append(embedded, ts(f.Type))
					continue
				}
				if tag == "" {
					tag = f.Name
				}
				fields = append(fields, fmt.Sprintf("%q: %s;", tag, ts(f.Type)))
			}
			def := "{\n" + strings.Join(fields, "\n") + "\n}"
			if len(embedded) > 0 {
				def = strings.Join(embedded, " & ") + " & " + def
			}
			defs[name] = def
		}
		return name
	}
	return "unknown"
}
func main() {
	v := reflect.TypeFor[*core.Service]()
	lines := []string{}
	seen := map[string]bool{}
	for _, name := range strings.Fields(webserver.Methods) {
		if seen[name] {
			continue
		}
		seen[name] = true
		m, ok := v.MethodByName(name)
		if !ok {
			panic(name)
		}
		args := []string{}
		for i := 1; i < m.Type.NumIn(); i++ {
			t := m.Type.In(i)
			if t == reflect.TypeFor[context.Context]() {
				continue
			}
			args = append(args, ts(t))
		}
		out := []string{}
		for i := 0; i < m.Type.NumOut(); i++ {
			t := m.Type.Out(i)
			if t == reflect.TypeFor[error]() {
				continue
			}
			out = append(out, ts(t))
		}
		result := "null"
		if len(out) == 1 {
			result = out[0]
		} else if len(out) > 1 {
			result = "[" + strings.Join(out, ",") + "]"
		}
		lines = append(lines, fmt.Sprintf("%s: {params: [%s]; result: %s};", name, strings.Join(args, ","), result))
	}
	keys := []string{}
	for k := range defs {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	b := strings.Builder{}
	b.WriteString("// Generated by go run ./cmd/godwit-web-types. Do not edit.\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "export type %s = %s;\n", k, defs[k])
	}
	b.WriteString("export interface Methods {\n" + strings.Join(lines, "\n") + "\n}\n")
	if e := os.WriteFile("web/src/browser/api-types.ts", []byte(b.String()), 0644); e != nil {
		panic(e)
	}
}
